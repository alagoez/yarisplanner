export type IconName = keyof typeof ICONS

type Props = {
  name: IconName
  size?: number
  strokeWidth?: number
  /** Pastel dolgu rengi; false verilirse dolgu çizilmez */
  fill?: string | false
  className?: string
}

export default function HandIcon({ name, size = 24, strokeWidth = 1.7, fill = 'var(--icon-fill)', className }: Props) {
  const def: IconDef = ICONS[name]
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
    >
      {fill && def.fill && (
        <g transform="translate(0.9 1)" fill={fill} stroke="none">
          {def.fill.map((d) => (
            <path key={d} d={d} />
          ))}
        </g>
      )}
      <g filter="url(#hand-wobble)">
        {def.d.map((d) => (
          <path key={d} d={d} />
        ))}
      </g>
    </svg>
  )
}

